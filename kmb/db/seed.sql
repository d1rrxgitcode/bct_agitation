-- Сначала нормализуем легаси-короткие имена в уже заполненных базах.
UPDATE ranks r SET name = v.new_name
FROM (VALUES
  ('PVT', 'PVT — Рядовой'),
  ('PFC', 'PFC — Рядовой первого класса'),
  ('CPL', 'CPL — Капрал'),
  ('JSG', 'JSG — Младший сержант'),
  ('SGT', 'SGT — Сержант'),
  ('HSG', 'HSG — Штаб-сержант'),
  ('JLT', 'JLT — Младший лейтенант'),
  ('LT',  'LT — Лейтенант'),
  ('SLT', 'SLT — Старший лейтенант'),
  ('CPT', 'CPT — Капитан')
) AS v(old_name, new_name)
WHERE r.name = v.old_name
  AND NOT EXISTS (SELECT 1 FROM ranks x WHERE x.name = v.new_name);

